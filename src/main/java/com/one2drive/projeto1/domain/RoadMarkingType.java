package com.one2drive.projeto1.domain;

/**
 * Road lane boundary marking types in Portuguese / European traffic law.
 * - DASHED (marca M2 - linha descontínua): transponível, allows lane change / overtaking.
 * - CONTINUOUS (marca M1 - linha contínua): intransponível, prohibits lane change / crossing.
 */
public enum RoadMarkingType {
    DASHED,
    CONTINUOUS
}
